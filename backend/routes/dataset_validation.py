@router.get("/results")
async def get_evaluation_results():
    """
    Returns actual calculated metrics from evaluation_results.json.
    """
    if not RESULTS_PATH.exists():
        return {
            "status": "not_evaluated",
            "message": "Evaluation not yet completed. Please execute backend/train_upper_limb_completion.py.",
            "results": None
        }

    try:
        with open(RESULTS_PATH, "r") as f:
            data = json.load(f)
        return {
            "status": "success",
            "results": data
        }
    except Exception as err:
        raise HTTPException(status_code=500, detail=f"Failed to read evaluation results: {err}")


@router.get("/test-cases")
async def get_test_cases():
    """
    Returns the list of 80 verified held-out test videos with ground-truth exercise & completion labels.
    """
    root = get_dataset_root()
    test_cases = []

    if root is not None:
        exercise_dir = root / "Exercise" if (root / "Exercise").exists() else root
        for r, _, files in os.walk(exercise_dir):
            for f in sorted(files):
                if f.endswith(".mp4"):
                    full_p = Path(r) / f
                    rel_parts = full_p.relative_to(root).parts
                    if "Test" in rel_parts:
                        ex_name = "Unknown"
                        label = "Unknown"
                        for p in rel_parts:
                            if "Lifting" in p or "Extending" in p or "Opening" in p:
                                ex_name = p.replace("1_", "").replace("2_", "").replace("3_", "").replace("4_", "")
                            elif p in ["Complete", "Incomplete"]:
                                label = p

                        test_cases.append({
                            "video_name": f,
                            "file_path": str(full_p),
                            "exercise": ex_name,
                            "ground_truth": label
                        })

    return {
        "count": len(test_cases),
        "test_cases": test_cases
    }


@router.post("/predict")
async def predict_dataset_video(
    file: Optional[UploadFile] = File(None),
    test_video_name: Optional[str] = Form(None)
):
    """
    Processes an uploaded video or selected dataset test video.
    Compares RehabShield prediction vs Ground Truth label (if known test case).
    """
    target_path = None
    known_ground_truth = None
    known_exercise = None
    is_dataset_case = False

    # Check if a known test video name was selected
    root = get_dataset_root()
    if test_video_name and root is not None:
        exercise_dir = root / "Exercise" if (root / "Exercise").exists() else root
        for r, _, files in os.walk(exercise_dir):
            if test_video_name in files:
                target_path = Path(r) / test_video_name
                rel_parts = target_path.relative_to(root).parts
                for p in rel_parts:
                    if "Lifting" in p or "Extending" in p or "Opening" in p:
                        known_exercise = p.replace("1_", "").replace("2_", "").replace("3_", "").replace("4_", "")
                    elif p in ["Complete", "Incomplete"]:
                        known_ground_truth = p
                is_dataset_case = True
                break

    # If an arbitrary MP4 video file was uploaded
    if target_path is None and file is not None:
        temp_dir = Path(__file__).parent.parent / "uploads"
        temp_dir.mkdir(parents=True, exist_ok=True)
        temp_file = temp_dir / f"val_{file.filename}"
        with open(temp_file, "wb") as f_out:
            content = await file.read()
            f_out.write(content)
        target_path = temp_file

    if target_path is None or not target_path.exists():
        raise HTTPException(status_code=400, detail="No valid video file or known dataset test video provided.")

    # Model Check
    if not MODEL_PATH.exists() or not SCALER_PATH.exists() or not ENCODER_PATH.exists():
        raise HTTPException(status_code=503, detail="Upper-limb completion model is not trained yet. Run train_upper_limb_completion.py first.")

    try:
        # 1. MediaPipe 14-D Upper-Limb Feature Extraction
        landmarker = init_landmarker()
        try:
            f_vec = extract_features_from_video_path(target_path, landmarker)
        finally:
            if hasattr(landmarker, "close"):
                try:
                    landmarker.close()
                except Exception:
                    pass

        if f_vec is None:
            return {
                "processing_status": "insufficient_pose_tracking",
                "message": "Tracking lost: Insufficient body landmark visibility to perform exercise completion classification.",
                "prediction": None,
                "confidence": None,
                "ground_truth": known_ground_truth,
                "match_status": "UNABLE_TO_PROCESS"
            }

        # 2. Model Prediction
        model = joblib.load(MODEL_PATH)
        scaler = joblib.load(SCALER_PATH)
        encoder = joblib.load(ENCODER_PATH)

        x_scaled = scaler.transform([f_vec])
        pred_idx = model.predict(x_scaled)[0]
        pred_probs = model.predict_proba(x_scaled)[0] if hasattr(model, "predict_proba") else [0.5, 0.5]
        
        pred_label = str(encoder.inverse_transform([pred_idx])[0])
        confidence = float(pred_probs[pred_idx]) * 100.0

        # Match calculation against ground truth if known dataset video
        match_status = "UNKNOWN_GROUND_TRUTH"
        if known_ground_truth:
            match_status = "MATCH" if (pred_label.lower() == known_ground_truth.lower()) else "MISMATCH"

        extracted_features_named = {
            name: round(float(val), 2)
            for name, val in zip(UPPER_LIMB_FEATURE_NAMES, f_vec)
        }

        return {
            "processing_status": "success",
            "video_name": target_path.name,
            "exercise": known_exercise or "Upper Limb Exercise",
            "prediction": pred_label,
            "confidence": round(confidence, 1),
            "ground_truth": known_ground_truth,
            "match_status": match_status,
            "is_dataset_case": is_dataset_case,
            "extracted_features": extracted_features_named
        }

    except Exception as err:
        logger.error(f"Error evaluating dataset video: {err}")
        raise HTTPException(status_code=500, detail=f"Failed to process dataset video: {err}")
